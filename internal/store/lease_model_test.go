package store

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"time"
)

var update = flag.Bool("update", false, "rewrite the formal models under formal/")

// leaseConstants is formal/LeaseConstants.tla: the lease's TTL and the
// renewal period, in the whole seconds the TLA+ model counts in. The TTL
// rounds down and the renewal up, so the model never gives a lease more
// room than the code does.
func leaseConstants() string {
	return fmt.Sprintf(`\* Code generated by TestLeaseConstants in internal/store. DO NOT EDIT.
-------------------------- MODULE LeaseConstants ---------------------------
Lease == %d
Renew == %d
=============================================================================
`, LeaseTTL/time.Second, (LeaseRenew+time.Second-1)/time.Second)
}

// TestLeaseConstants holds formal/LeaseConstants.tla to the Go constants, so
// the tla gate checks formal/Lease.tla against the TTL and renewal period
// the jobs run with. Rerun with -update after changing one.
func TestLeaseConstants(t *testing.T) {
	path := filepath.Join("..", "..", "formal", "LeaseConstants.tla")
	want := leaseConstants()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; rerun with -update", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s differs from the lease constants; rerun go test ./internal/store -run TestLeaseConstants -update\n--- want\n%s--- got\n%s", path, want, got)
	}
}
